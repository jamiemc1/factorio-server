// Package server prepares the data volume and assembles the Factorio server
// command line. It is a Go port of the factoriotools base image's
// /docker-entrypoint.sh, which the supervisor used to exec as a child process.
//
// Dropped from the original on purpose: PUID/PGID + runuser (the supervisor is
// the only tenant of its VM and runs as root), the box64 ARM emulation path,
// pwgen (RCON_PASSWORD is a secret and the supervisor writes rconpw itself), and
// UPDATE_MODS_ON_START (internal/mods owns mod synchronisation).
package server

import (
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"

	"github.com/thomasalbrighton/factorio-supervisor/internal/config"
	"github.com/thomasalbrighton/factorio-supervisor/internal/gameinstall"
)

// Launcher prepares the volume and builds the server invocation.
type Launcher struct {
	cfg  *config.Config
	logf func(string, ...any)
}

// New builds a Launcher.
func New(cfg *config.Config, logf func(string, ...any)) *Launcher {
	if logf == nil {
		logf = func(string, ...any) {}
	}
	return &Launcher{cfg: cfg, logf: logf}
}

// SeedVolume creates the directory tree on the data volume and copies the
// config and mod-list defaults baked into the image over it. Seeding overwrites
// on every boot so server-settings.json and mods/public.json stay
// image-authoritative — changing them is a redeploy, exactly as before.
func (l *Launcher) SeedVolume() error {
	c := l.cfg
	for _, dir := range []string{c.ConfigDir, c.SavesDir, c.ModsDir, c.PrivateModsDir, c.ScenariosDir, c.ScriptOutputDir} {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return fmt.Errorf("create %s: %w", dir, err)
		}
	}

	if err := copyTree(filepath.Join(c.DefaultsDir, "config"), c.ConfigDir); err != nil {
		return fmt.Errorf("seed config: %w", err)
	}
	if err := copyTree(filepath.Join(c.DefaultsDir, "mods"), c.ModsDir); err != nil {
		return fmt.Errorf("seed mods: %w", err)
	}
	l.logf("Seeded %s from %s", filepath.Dir(c.ConfigDir), c.DefaultsDir)
	return nil
}

// WriteConfigINI writes the config.ini passed to the server with --config. It is
// rewritten on every boot because read-data points into the versioned install
// directory, which moves on upgrade.
func (l *Launcher) WriteConfigINI(installDir string) (string, error) {
	path := filepath.Join(l.cfg.ConfigDir, "config.ini")
	body := fmt.Sprintf("; Generated by factorio-supervisor; edits are overwritten on boot.\n"+
		"[path]\nread-data=%s\nwrite-data=%s\n\n[general]\nlocale=\n",
		gameinstall.DataDir(installDir), filepath.Dir(l.cfg.ConfigDir))
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
		return "", err
	}
	return path, nil
}

// CleanTempSaves removes partial saves left behind by a forced exit; Factorio
// refuses to start if it finds one.
func (l *Launcher) CleanTempSaves() error {
	matches, err := filepath.Glob(filepath.Join(l.cfg.SavesDir, "*.tmp.zip"))
	if err != nil {
		return err
	}
	for _, m := range matches {
		l.logf("Removing incomplete save %s", filepath.Base(m))
		if err := os.Remove(m); err != nil {
			return err
		}
	}
	return nil
}

// EnsureSave generates a new map when asked to, or when the saves directory is
// empty and there is therefore nothing to load.
func (l *Launcher) EnsureSave(installDir, configPath string) error {
	c := l.cfg
	generate := c.GenerateNewSave
	saveName := c.SaveName

	if !generate {
		existing, err := filepath.Glob(filepath.Join(c.SavesDir, "*.zip"))
		if err != nil {
			return err
		}
		if len(existing) == 0 {
			l.logf("No saves present — generating a new map")
			generate = true
			saveName = "_autosave1"
		}
	}
	if !generate {
		return nil
	}
	if saveName == "" {
		return fmt.Errorf("GENERATE_NEW_SAVE is true but SAVE_NAME is empty")
	}

	target := filepath.Join(c.SavesDir, saveName+".zip")
	if _, err := os.Stat(target); err == nil {
		l.logf("Map %s already exists, skipping map generation", target)
		return nil
	}

	args := []string{
		"--config", configPath,
		"--create", target,
		"--map-gen-settings", filepath.Join(c.ConfigDir, "map-gen-settings.json"),
		"--map-settings", filepath.Join(c.ConfigDir, "map-settings.json"),
		"--mod-directory", c.ModsDir,
	}
	if c.Preset != "" {
		args = append(args, "--preset", c.Preset)
	}

	l.logf("Creating map %s", target)
	cmd := exec.Command(gameinstall.Binary(installDir), args...)
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("create map: %w", err)
	}
	return nil
}

// Args assembles the server command line, mirroring the flag list the base
// image's entrypoint used. extra is appended verbatim (supervisor passthrough
// arguments).
func (l *Launcher) Args(installDir, configPath string, extra []string) ([]string, error) {
	c := l.cfg

	password, err := os.ReadFile(c.RCONPasswordFile)
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", c.RCONPasswordFile, err)
	}

	args := []string{
		"--config", configPath,
		"--port", strconv.Itoa(c.GamePort),
		"--rcon-port", strconv.Itoa(c.RCONPort),
		"--rcon-password", string(password),
		"--server-settings", c.ServerSettingsPath,
		"--server-banlist", filepath.Join(c.ConfigDir, "server-banlist.json"),
		"--server-whitelist", filepath.Join(c.ConfigDir, "server-whitelist.json"),
		"--use-server-whitelist",
		"--server-adminlist", filepath.Join(c.ConfigDir, "server-adminlist.json"),
		"--server-id", filepath.Join(c.ConfigDir, "server-id.json"),
		"--mod-directory", c.ModsDir,
	}
	if c.ConsoleLogLocation != "" {
		args = append(args, "--console-log", c.ConsoleLogLocation)
	}
	if c.Bind != "" {
		args = append(args, "--bind", c.Bind)
	}
	if c.LoadLatestSave {
		args = append(args, "--start-server-load-latest")
	} else {
		args = append(args, "--start-server", filepath.Join(c.SavesDir, c.SaveName+".zip"))
	}
	return append(args, extra...), nil
}

// copyTree copies src over dst recursively, overwriting existing files. A
// missing src is not an error — it just means the image baked no defaults.
func copyTree(src, dst string) error {
	info, err := os.Stat(src)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	if !info.IsDir() {
		return copyFile(src, dst, info.Mode().Perm())
	}
	entries, err := os.ReadDir(src)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(dst, 0o755); err != nil {
		return err
	}
	for _, e := range entries {
		from, to := filepath.Join(src, e.Name()), filepath.Join(dst, e.Name())
		if e.IsDir() {
			if err := copyTree(from, to); err != nil {
				return err
			}
			continue
		}
		fi, err := e.Info()
		if err != nil {
			return err
		}
		if err := copyFile(from, to, fi.Mode().Perm()); err != nil {
			return err
		}
	}
	return nil
}

func copyFile(src, dst string, mode os.FileMode) error {
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()
	out, err := os.OpenFile(dst, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, mode)
	if err != nil {
		return err
	}
	if _, err := io.Copy(out, in); err != nil {
		out.Close()
		return err
	}
	return out.Close()
}
